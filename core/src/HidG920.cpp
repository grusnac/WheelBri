void putAxis(std::array<std::uint8_t, kG920InputReportSize>& out, std::size_t at, std::int32_t value) {
    const auto v = static_cast<std::int16_t>(std::clamp<std::int32_t>(value - 32768, -32768, 32767));
    out[at] = static_cast<std::uint8_t>(static_cast<std::uint16_t>(v) & 0xFFU);
    out[at + 1] = static_cast<std::uint8_t>(static_cast<std::uint16_t>(v) >> 8U);
}

