std::span<const VirtualWheel> virtualWheels() { return kVirtualWheels; }

const VirtualWheel* virtualWheel(const std::string_view profile) {
    for (const VirtualWheel& wheel : kVirtualWheels) {
        if (wheel.profile == profile) return &wheel;
    }
    return nullptr;
}

const VirtualWheel* virtualWheelForHardwareId(const std::string_view hardwareId) {
    for (const VirtualWheel& wheel : kVirtualWheels) {
        if (sameIgnoringCase(wheel.hardwareId, hardwareId)) return &wheel;
    }
    return nullptr;
}

bool isVirtualWheelId(const std::uint16_t vendorId, const std::uint16_t productId) {
    for (const VirtualWheel& wheel : kVirtualWheels) {
        if (wheel.vendorId == vendorId && wheel.productId == productId) return true;
    }
    return false;
}

std::span<const std::uint8_t> g920ReportDescriptor(const std::size_t buttons) {
    if (buttons >= kG923Buttons) return kG923Descriptor;
    if (buttons > kG920Buttons) return kG27Descriptor;
    return kDescriptor;
}

std::span<const std::uint8_t> g920ProtonReportDescriptor() { return kProtonDescriptor; }

std::array<std::uint8_t, kG920InputReportSize> packG920Input(const TargetReport& report, const std::size_t buttonCount) {
    std::array<std::uint8_t, kG920InputReportSize> out{};
    out[0] = kG920InputReportId;
    putAxis(out, 1, report.steering);
    putAxis(out, 3, report.throttle);   // Y
    putAxis(out, 5, report.brake);      // Rz
    putAxis(out, 7, report.clutch);     // Slider
    // The descriptor's buttons only (19, the shifter's included; the G27's 23, the G923's 24): the rest are padding.
    const std::size_t count = buttonCount >= kG923Buttons ? kG923Buttons
                              : buttonCount > kG920Buttons ? kG27Buttons
                                                           : kG920Buttons;
    const std::uint32_t buttons = report.buttons & ((1U << count) - 1U);
    out[9] = static_cast<std::uint8_t>(buttons & 0xFFU);
    out[10] = static_cast<std::uint8_t>((buttons >> 8U) & 0xFFU);
    out[11] = static_cast<std::uint8_t>((buttons >> 16U) & 0xFFU);
    out[12] = report.hat >= 0 && report.hat <= 7 ? static_cast<std::uint8_t>(report.hat) : 8;   // 8 = centred
    return out;
}

TargetReport g920Neutral() {
    TargetReport r;
    r.steering = 32768;
    r.throttle = 65535;
    r.brake = 65535;
    r.clutch = 65535;
    r.buttons = 0;
    r.hat = kHatCentered;
    return r;
}

