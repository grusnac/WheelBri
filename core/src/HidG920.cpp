std::array<std::uint8_t, kG920InputReportSize> packG920Input(const TargetReport& report) {
    std::array<std::uint8_t, kG920InputReportSize> out{};
    out[0] = kG920InputReportId;
    putAxis(out, 1, report.steering);
    putAxis(out, 3, report.brake);
    putAxis(out, 5, report.clutch);
    putAxis(out, 7, report.throttle);
    out[9] = static_cast<std::uint8_t>(report.buttons & 0xFFU);
    out[10] = static_cast<std::uint8_t>((report.buttons >> 8U) & 0x07U);   // 11 real buttons
    out[11] = report.hat >= 0 && report.hat <= 7 ? static_cast<std::uint8_t>(report.hat) : 8;   // 8 = centred
    return out;
}

